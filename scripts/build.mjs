// Builds dist/esm (ES modules) and dist/cjs (CommonJS), each with type declarations.
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const tsc = require.resolve('typescript/bin/tsc');

// package.json is the only place the version is set; src/version.ts follows it on every build.
const { version } = JSON.parse(readFileSync('package.json', 'utf8'));
const versionTs = `// Generated by scripts/build.mjs from package.json. Do not edit.\nexport const VERSION = '${version}';\n`;
if (readFileSync('src/version.ts', 'utf8') !== versionTs) writeFileSync('src/version.ts', versionTs);

rmSync('dist', { recursive: true, force: true });
execFileSync(process.execPath, [tsc, '-p', 'tsconfig.json'], { stdio: 'inherit' });
execFileSync(process.execPath, [tsc, '-p', 'tsconfig.cjs.json'], { stdio: 'inherit' });
mkdirSync('dist/esm', { recursive: true });
writeFileSync('dist/esm/package.json', JSON.stringify({ type: 'module' }) + '\n');
writeFileSync('dist/cjs/package.json', JSON.stringify({ type: 'commonjs' }) + '\n');
